export type ProgramDifficulty = "beginner" | "intermediate" | "advanced";

/**
 * Для кого программа. «Публичная» — автор создал её как программу для
 * других участников сообщества; «личная» — автор сам по ней тренируется.
 * Отметка автора для каталога, а не права доступа: видимость программы
 * по-прежнему определяется только публикацией версии.
 */
export type ProgramCategory = "public" | "personal";

export type ProgramVersionStatus = "draft" | "published";

/**
 * Режим схемы. «Свободная» — всё текстом, система ничего не разбирает
 * (как было всегда). «Автоматическая» — автор вводит числа (повторения
 * или секунды, число кругов, отдых), и по схеме можно проходить
 * тренировку с таймерами. Автоматическая схема публикуется только
 * заполненной целиком (см. utils/programAuto.ts).
 */
export type ProgramSchemeMode = "free" | "auto";

/** Ориентир для упражнения в автоматической схеме: повторения,
 *  секунды, «максимум» или AMRAP. Это рекомендация — фактический
 *  результат человек вводит сам. value пустое, пока автор не ввёл число
 *  (в черновике). У «максимума» value — примерное число повторений: во
 *  время выполнения человеку показывается слово «Максимум», а после
 *  подхода результат отмечается начиная с этого числа. У AMRAP value —
 *  секунды таймера (как можно больше повторений за это время),
 *  повторения считаются всегда: reps — примерный результат. У EMOM
 *  value — секунды одного интервала: таймер идёт до нуля и сам
 *  запускается заново на каждый подход (число подходов — как у
 *  комплекса); повторения считаются всегда, reps — примерное число
 *  повторений за интервал. */
export type ProgramTargetKind = "reps" | "seconds" | "max" | "amrap" | "emom";

export type ProgramItemTarget = {
    kind: ProgramTargetKind;
    value?: number;

    /** Только для «секунд»: считать ли ещё и повторения, которые
     *  человек сделает за это время (подтягивания за 30 секунд). Для
     *  статических упражнений («Всадник») не нужно. */
    withReps?: boolean;

    /** Ориентировочное число повторений за это время. Человеку во
     *  время выполнения не показывается: после подхода он сам отметит,
     *  сколько сделал, а это число подставляется как значение по
     *  умолчанию. */
    reps?: number;
};

/**
 * Порядок сетов в комплексе автоматической схемы:
 * sequential — «по очереди» (сет 1 несколько раз, затем сет 2);
 * interleaved — «по кругу» (сет 1, сет 2 … и так несколько раз подряд).
 */
export type ProgramBlockOrder = "sequential" | "interleaved";

/**
 * Одно упражнение блока: из базы упражнений (на него ссылаются, его
 * мышцы идут в картинку схемы) или своим текстом автора (упражнение,
 * которого нет в базе — остаётся обычной строкой). Ссылки и свой текст
 * могут чередоваться: порядок задаёт автор.
 *
 * load — нагрузка в этом упражнении, необязательная и свободным
 * текстом: «20 повторений», «максимум», «технический максимум», «80% от
 * максимума», «30 секунд». Система её не разбирает и не интерпретирует
 * (п.18 документа).
 */
export type ProgramBlockItem = (
    | { kind: "exercise"; exerciseId: string; load?: string }
    | { kind: "text"; text: string; load?: string }
) & {
    /** Только автоматические схемы: ориентир (повторения/секунды). */
    target?: ProgramItemTarget;

    /** Вес со знаком: плюс — утяжелитель, минус — помощь (резинка,
     *  гравитрон). Нет — без дополнительного веса. */
    weightKg?: number;

    /** Только автоматические схемы: упражнение входит в один сет с
     *  предыдущим (суперсет). У первого упражнения не учитывается. */
    groupWithPrevious?: boolean;

    /** Только автоматические схемы: сколько подходов в сете. Задаётся у
     *  первого упражнения сета и нужно при нескольких сетах «по
     *  очереди» (у каждого сета своё число); если не задано, берётся
     *  ProgramBlock.rounds. */
    rounds?: number;
};

/**
 * Блок — минимальная структурированная часть схемы (см. UX-документ
 * «Раздел Программы», п.12-17). В интерфейсе называется "Комплекс" —
 * то же самое поле структуры, просто более привычное тренирующимся
 * слово; имя типа/поля на фронтенде и бэкенде не меняем. Название
 * обязательно, всё остальное — свободный текст автора, который
 * фронтенд никак не разбирает и не анализирует.
 */
export type ProgramBlock = {
    /** Клиентский id для стабильных React-ключей при редактировании
     *  порядка — на бэкенде не осмысливается, просто хранится. */
    id: string;

    title: string;

    /** Порядок элементов этого списка — и есть порядок выполнения,
     *  который увидят пользователи (п.15). У старых версий упражнения
     *  хранились просто строками — при чтении они превращаются в
     *  элементы kind: "text" (см. api/mappers/program.ts). */
    items: ProgramBlockItem[];

    /** "Схема / описание выполнения блока" (п.16), например "5 × 10". */
    scheme?: string;

    note?: string;

    /** Отдых между подходами/комплексами — свободный текст автора,
     *  например "60-90 секунд" или "полное восстановление". */
    rest?: string;

    // --- Только автоматические схемы (см. ProgramSchemeMode) ---------
    // Подряд идущие упражнения образуют «сет», если у следующего
    // groupWithPrevious; иначе каждое упражнение — отдельный сет.

    /** Сколько раз повторяется комплекс: число кругов (порядок «по
     *  кругу»), число подходов единственного сета, а при нескольких
     *  сетах «по очереди» — значение по умолчанию для сетов, у которых
     *  нет своего числа подходов (ProgramBlockItem.rounds). */
    rounds?: number;

    order?: ProgramBlockOrder;

    /** Отдых в секундах: между упражнениями внутри сета. */
    restWithinSet?: number;

    /** Между подходами или кругами. */
    restBetweenRounds?: number;

    /** Между сетами. */
    restBetweenSets?: number;

    /** После комплекса, перед следующим. */
    restAfterBlock?: number;

    /** EMOM: в сетах, где все цели — EMOM, упражнения выполняются не по
     *  очереди (у каждого свой интервал), а все вместе за один
     *  интервал. Секунды интервала — у первого упражнения сета (у
     *  остальных то же число). */
    emomTogether?: boolean;
};

export type ProgramScheme = {
    id: string;

    name: string;

    description?: string;

    blocks: ProgramBlock[];

    note?: string;

    /** "Дополнительные материалы" (п.11) — ссылка/текст. */
    extraMaterials?: string;

    /** Не указан — значит «free» (старые схемы). */
    mode?: ProgramSchemeMode;
};

/**
 * Раздел — необязательный уровень вложенности (п.10). Когда автор не
 * использует разделы, вся структура хранится как один раздел с
 * name=undefined — на экране такой раздел не показывается отдельным
 * заголовком, см. ProgramStructureView/ProgramStructureEditor.
 */
export type ProgramSection = {
    id: string;

    name?: string;

    schemes: ProgramScheme[];
};

export type ProgramStructure = {
    sections: ProgramSection[];
};

export type ProgramVersion = {
    id: string;

    programId: string;

    status: ProgramVersionStatus;

    versionNumber?: string;

    changelog?: string;

    structure: ProgramStructure;

    createdAt: string;

    updatedAt: string;

    publishedAt?: string;
};

/** Для истории версий (без структуры целиком, см. п.4.1 документа). */
export type ProgramVersionSummary = {
    id: string;

    versionNumber?: string;

    changelog?: string;

    publishedAt?: string;
};

/**
 * Программа из каталога — приходит с GET /programs. Автор — любой
 * зарегистрированный пользователь (в отличие от Complex, который
 * ведёт только администратор), поэтому здесь есть поля об авторе.
 */
export type Program = {
    id: string;

    title: string;

    description: string;

    coverUrl?: string;

    difficulty?: ProgramDifficulty;

    category: ProgramCategory;

    authorId: string;

    authorNickname: string;

    authorAvatarUrl?: string;

    /** Есть ли хотя бы одна опубликованная версия (п.3 документа) —
     *  пока false, программа видна только автору. */
    isPublished: boolean;

    currentVersionId?: string;

    trainingsCount: number;

    favoritesCount: number;

    isFavoritedByViewer: boolean;

    createdAt: string;

    updatedAt: string;
};
