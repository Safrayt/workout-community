/**
 * Markdown → короткий обычный текст: для карточки программы в каталоге и
 * описания страницы для поисковиков. Картинки и карусели выбрасываются,
 * у ссылок остаётся только текст, значки разметки убираются.
 */
export function markdownToPlainText(source: string | null | undefined): string {
    return (source ?? "")
        // Блоки кода (в том числе ```carousel с картинками) целиком.
        .replace(/```[\s\S]*?```/g, " ")
        // Картинки.
        .replace(/!\[[^\]]*\]\([^)]*\)/g, " ")
        // Ссылки: оставляем текст.
        .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
        // Сырой HTML.
        .replace(/<[^>]*>/g, " ")
        // Маркеры заголовков, цитат и списков в начале строки.
        .replace(/^\s{0,3}(?:#{1,6}\s+|>\s?|[-*+]\s+|\d+\.\s+)/gm, "")
        // Таблицы: разделители строк и столбцов.
        .replace(/^\s*\|?[\s:|-]+\|[\s:|-]*$/gm, " ")
        .replace(/\|/g, " ")
        // Выделение и код.
        .replace(/[*_~`]+/g, "")
        .replace(/\s+/g, " ")
        .trim();
}
